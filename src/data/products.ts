export function formatProductPrice(product: Product, quantity = 1): string {
  if (product.price === null) {
    return product.priceLabel || 'Call for price';
  }
  const base = `Rs. ${(product.price * quantity).toLocaleString()}`;
  if (quantity === 1 && product.priceUnitNote) {
    return `${base} ${product.priceUnitNote}`;
  }
  return base;
}

export function formatUnitPrice(product: Product): string {
  if (product.price === null) {
    return product.priceLabel || 'Call for price';
  }
  return product.priceUnitNote
    ? `Rs. ${product.price.toLocaleString()} ${product.priceUnitNote}`
    : `Rs. ${product.price.toLocaleString()}`;
}

